use bevy::prelude::*;
use serde::{Deserialize, Serialize};
use unevents_core::events::roomchanged::InteractionExecutionType;
use unghost_core::types::evidence::Evidence;
use unghost_core::types::ghost::types::GhostType;

/// Sent by the (room-owner) client to request a map change.
///
/// On the server this arrives as `FromClient<RequestSelectMap>`.
/// The server validates ownership then updates `LobbyInfo.selected_map`.
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct RequestSelectMap {
    pub map_filepath: String,
}

/// Sent by the (room-owner) client to request a difficulty change.
///
/// On the server this arrives as `FromClient<RequestSelectDifficulty>`.
/// The server validates ownership then updates `LobbyInfo.selected_difficulty`.
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct RequestSelectDifficulty {
    pub difficulty_id: String,
}

/// Sent by the (room-owner) client to start the mission.
///
/// `map_seed` is generated by the sender so all peers use the same value.
/// On the server this arrives as `FromClient<RequestStartMission>`.
/// The server spawns a `(Replicated, SelectedMission)` entity which clients
/// observe to trigger level loading.
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct RequestStartMission {
    pub map_seed: u64,
}

// ---------------------------------------------------------------------------
// Phase 3: Players, Movement, and Interactions
// ---------------------------------------------------------------------------

/// Sent each frame by a non-host client to report its current position and state.
///
/// Sent over `Channel::Unreliable` (best-effort, unordered). The server validates
/// and writes to `NetworkPosition` + `PlayerStateNet`, after which replicon
/// propagates the update to all other connected clients.
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct PlayerMoveMessage {
    pub x: f32,
    pub y: f32,
    pub z: f32,
    pub is_running: bool,
    /// Current animation frame index (for remote character animation sync).
    pub frame: u16,
    pub is_hiding: bool,
    pub stamina: f32,
    pub health: f32,
    pub sanity: f32,
}

/// Sent by a client to request an interactive-object state change.
///
/// Uses board-space integer coordinates to identify the target entity in a
/// map-stable way (all clients load the same map from the same seed).
/// The server finds the entity at `position`, validates the request, and fires
/// `ExecuteInteractionEvent` locally.
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct InteractionRequestMessage {
    /// Board-space position (`[x, y, z]`) of the interactive entity.
    pub position: [i32; 3],
    /// Whether to change state or only read the current room state.
    pub ietype: InteractionExecutionType,
    /// If `Some`, force the interaction to transition to this specific tile UID.
    pub force_tuid: Option<u32>,
}

// ---------------------------------------------------------------------------
// Phase 4: Ghost, Evidence, and Mission messages
// ---------------------------------------------------------------------------

/// Broadcast by the server to all clients to spawn a visual particle effect.
///
/// Registered as a server → client message via `app.add_server_message`.
/// Clients receive this and spawn the particle entity locally.
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct SpawnParticleNetEvent {
    /// Particle type identifier (currently only "smoke").
    pub particle_type: String,
    /// World-space position `[x, y, z]` at which to spawn the particle.
    pub position: [f32; 3],
}

/// Sent by a client to toggle evidence in the shared journal.
///
/// The server validates this, updates `GhostGuess`, and the change propagates
/// to all clients via `EvidenceFoundNet` replication.
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct RequestJournalEvidenceToggle {
    pub evidence: Evidence,
    pub mark_as_found: bool,
}

/// Sent by a client to update the ghost-type guess in the shared journal.
///
/// `ghost_type = None` means "clear the current guess".
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct RequestJournalGhostToggle {
    pub ghost_type: Option<GhostType>,
}
