/// Broadcast by the server to all clients to spawn a visual particle effect.
///
/// Registered as a server → client message via `app.add_server_message`.
/// Clients receive this and spawn the particle entity locally.
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct SpawnParticleNetEvent {
    /// Particle type identifier (currently only "smoke").
    pub particle_type: String,
    /// World-space position `[x, y, z]` at which to spawn the particle.
    pub position: [f32; 3],
}

/// Sent by the Authority when the ghost-talk RNG fires in `sound_update`
/// (the `gn == 0` block). All pure clients receive this and inject a
/// sound-field pulse into their local `SoundGrid` at the same time as the
/// Authority, synchronizing the *trigger timing* of ghost-induced sanity
/// pressure. Each client reconstructs the pulse independently with local RNG,
/// so the exact vector magnitudes are not identical across instances.
///
/// One message is sent per `SoundEmitter` entity that exists at the time of
/// the trigger (normally: ghost breach + ghost entity = two messages per event).
#[derive(Debug, Clone, Serialize, Deserialize, Message)]
pub struct GhostSoundFieldBroadcast {
    /// World-space position of the emitter entity (breach or ghost).
    pub position: [f32; 3],
}

/// Local-only Bevy event emitted by the Hub UI layer when a room connection
/// is requested from the server. This event is listened to by the transport layer
/// (unreplicon-plugin) to handle the actual connection setup and mutation of
/// network state, rather than having the UI layer mutate global config directly.
///
/// This maintains the "Tell, Don't Ask" pattern: the UI layer (domain) emits
/// a signal; the transport layer (infrastructure) receives and acts on it.
#[derive(Debug, Clone, Message)]
pub struct HubConnectionRequested {
    pub address: String,
    pub ticket: Option<String>,
}
